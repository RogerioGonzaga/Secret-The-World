import type {
  City,
  CitySize,
  CityTag,
  ClimateType,
  CostItemId,
  IndicatorId,
  ProfessionId,
  Setting,
} from "@/lib/domain/types";
import { COST_ITEMS, INDICATORS, PROFESSIONS } from "@/lib/domain/types";
import { countryBySlug } from "./countries";
import { DEMO, editorial } from "./sources";

/**
 * Cidades da versão inicial.
 *
 * ATENÇÃO — integridade dos dados:
 * - Custos, salários, indicadores de qualidade de vida e temperaturas mensais são DEMONSTRATIVOS
 *   (fonte "livora-demo"): servem para exercitar a interface e os cálculos e são sinalizados na tela.
 * - População é uma estimativa editorial aproximada, com o instituto de referência indicado,
 *   pendente de verificação.
 * - Moeda, idioma e fuso horário são fatos de referência estáveis (ISO 4217 / IANA).
 *
 * Para adicionar uma cidade, inclua um item abaixo; a página /destinos/[slug] é gerada automaticamente.
 */

type Tuple12 = [number, number, number, number, number, number, number, number, number, number, number, number];

interface CityInput {
  slug: string;
  name: string;
  country: string;
  lat: number;
  lng: number;
  tz: string;
  population: [value: number, year: string, institute: string];
  size: CitySize;
  settings: Setting[];
  image: [unsplashId: string, alt: string];
  summary: string;
  pros: string[];
  cons: string[];
  climate: [type: ClimateType, summary: string, monthlyHighC: Tuple12];
  /** Ordem de COST_ITEMS, moeda local, valores mensais. */
  costs: Tuple12;
  /** [mediana, ...PROFESSIONS] — salário bruto mensal em moeda local; null = sem dado. */
  salaries: [median: number | null, ...byProfession: (number | null)[]];
  /** Ordem de INDICATORS, escala 0–100; null = dados indisponíveis. */
  quality: (number | null)[];
  demand: string[];
  remoteFriendly: boolean;
  modes: string;
  housingTypes: string[];
  centerVsOutside: string;
  tags: CityTag[];
}

function unsplash(id: string) {
  return `https://images.unsplash.com/${id}?auto=format&fit=crop&w=1600&q=75`;
}

function build(input: CityInput): City {
  const country = countryBySlug.get(input.country);
  if (!country) throw new Error(`País desconhecido para ${input.slug}: ${input.country}`);
  const currency = country.currencyCode;

  const items = Object.fromEntries(COST_ITEMS.map((id, i) => [id, input.costs[i]])) as Record<CostItemId, number>;
  const [median, ...prof] = input.salaries;
  const byProfession: Partial<Record<ProfessionId, number>> = {};
  PROFESSIONS.forEach((id, i) => {
    const v = prof[i];
    if (typeof v === "number") byProfession[id] = v;
  });
  const quality = Object.fromEntries(
    INDICATORS.map((id, i) => [id, { score: input.quality[i] ?? null, provenance: DEMO }]),
  ) as Record<IndicatorId, { score: number | null; provenance: typeof DEMO }>;

  return {
    slug: input.slug,
    name: input.name,
    countrySlug: input.country,
    coordinates: { lat: input.lat, lng: input.lng },
    timezone: input.tz,
    population: {
      value: input.population[0],
      provenance: editorial(input.population[1], `Aproximação baseada em ${input.population[2]}. Limites municipais e metropolitanos variam.`),
    },
    size: input.size,
    settings: input.settings,
    image: {
      url: unsplash(input.image[0]),
      alt: input.image[1],
      credit: "Unsplash",
      creditUrl: "https://unsplash.com/license",
    },
    summary: input.summary,
    pros: input.pros,
    cons: input.cons,
    climate: {
      type: input.climate[0],
      summary: input.climate[1],
      monthlyHighC: { value: input.climate[2], provenance: { ...DEMO, unit: "°C", notes: "Médias de máxima mensais aproximadas, demonstrativas." } },
    },
    costs: { currency, items, provenance: { ...DEMO, currency, unit: "por mês" } },
    salaries: {
      currency,
      basis: "gross_monthly",
      median: median ?? null,
      byProfession,
      provenance: { ...DEMO, currency, unit: "bruto por mês" },
    },
    quality,
    work: { demandAreas: input.demand, remoteFriendly: input.remoteFriendly, modes: input.modes },
    housing: { types: input.housingTypes, centerVsOutside: input.centerVsOutside },
    tags: input.tags,
  };
}

